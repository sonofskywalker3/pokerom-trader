/* Local LE helpers (a decrypted PK4 stores its party stats little-endian). */
static inline void wr16(uint8_t *p, uint16_t v)
{
    p[0] = (uint8_t)(v & 0xFF);
    p[1] = (uint8_t)(v >> 8);
}

/* Growth-rate group codes (match gen3_stats.c). */
