uint8_t gen4_ability_id(uint16_t national_dex, int slot)
{
    if (national_dex < 1 || national_dex > GEN4_NATIONAL_DEX_MAX || slot < 0 || slot > 1)
    {
        return 0;
    }
    return gen4_ability_table[national_dex][slot];
}

uint32_t gen4_exp_for_level(int n, uint8_t growth_rate)
{
    if (n <= 1)
    {
        return 0;
    }
    long long L = n;
    long long e = 0;
    switch (growth_rate)
    {
    case GR_FAST:
        e = 4 * L * L * L / 5;
        break;
    case GR_MEDIUM_FAST:
        e = L * L * L;
        break;
    case GR_MEDIUM_SLOW:
        e = 6 * L * L * L / 5 - 15 * L * L + 100 * L - 140;
        break;
    case GR_SLOW:
        e = 5 * L * L * L / 4;
        break;
    case GR_ERRATIC:
        if (L < 50)
            e = L * L * L * (100 - L) / 50;
        else if (L < 68)
            e = L * L * L * (150 - L) / 100;
        else if (L < 98)
            e = L * L * L * ((1911 - 10 * L) / 3) / 500;
        else
            e = L * L * L * (160 - L) / 100;
        break;
    case GR_FLUCTUATING:
        if (L < 15)
            e = L * L * L * ((L + 1) / 3 + 24) / 50;
        else if (L < 36)
            e = L * L * L * (L + 14) / 50;
        else
            e = L * L * L * (L / 2 + 32) / 50;
        break;
    default:
        e = L * L * L;
        break;
    }
    if (e < 0)
    {
        e = 0;
    }
    return (uint32_t)e;
}

int gen4_level_from_exp(uint32_t exp, uint8_t growth_rate)
{
    int level = 1;
    for (int L = 2; L <= 100; L++)
    {
        if (gen4_exp_for_level(L, growth_rate) <= exp)
        {
            level = L;
        }
        else
        {
            break;
        }
    }
    return level;
}

/* One stat via the Gen 3/4 formula. is_hp changes the +level+10 vs +5 tail. */
static uint16_t gen4_calc_stat(bool is_hp, uint8_t base, uint8_t iv, uint8_t ev, int level, int nature_num, int nature_den)
{
    int common = (2 * base + iv + ev / 4) * level / 100;
    if (is_hp)
    {
        return (uint16_t)(common + level + 10);
    }
    int stat = common + 5;
    stat = stat * nature_num / nature_den; // 11/10, 9/10, or 1/1
    return (uint16_t)stat;
}

bool gen4_build_party_stats(uint8_t *dec)
{
    uint16_t dex = gen4_pk4_species(dec);
    if (dex == 0 || dex > GEN4_NATIONAL_DEX_MAX || gen4_pk4_is_egg(dec))
    {
        return false; // empty / egg / out-of-range: cannot build legal stats
    }
    const struct g4_base *base = &gen4_base_stats[dex];
    if (base->hp == 0)
    {
        return false; // no base-stat data (shouldn't happen for a real species)
    }

    uint8_t growth = gen4_growth_rate[dex];
    int level = gen4_level_from_exp(gen4_pk4_exp(dec), growth);
    if (level < 1) level = 1;
    if (level > 100) level = 100;

    // Nature (0-24) from the PID. raise/lower index into the five non-HP stats
    // in party order: 0=Atk 1=Def 2=Spe 3=SpA 4=SpD.
    int nature = (int)(gen4_pk4_pid(dec) % 25);
    int raise = nature / 5;
    int lower = nature % 5;
    int num[5] = {1, 1, 1, 1, 1};
    int den[5] = {1, 1, 1, 1, 1};
    if (raise != lower)
    {
        num[raise] = 11; den[raise] = 10;
        num[lower] = 9;  den[lower] = 10;
    }

    // EVs/IVs are ordered HP,Atk,Def,Spe,SpA,SpD (index 0..5) via the accessors.
    uint8_t iv_hp = gen4_pk4_iv(dec, 0);
    uint8_t ev_hp = gen4_pk4_ev(dec, 0);
    // Non-HP stats: base values in party order match num[]/den[] and EV/IV i+1.
    uint8_t nonhp_base[5] = {base->atk, base->def, base->spe, base->spa, base->spd};

    // Rebuild the whole 100-byte party-stats region (0x88..0xEB) from scratch:
    // status(0x88) = 0, level(0x8C), current/max HP, five battle stats; the
    // trailing capsule/seal bytes (0x9C..) are zero for a freshly-derived mon.
    memset(dec + 0x88, 0, 100);
    dec[0x8C] = (uint8_t)level;

    uint16_t max_hp = (base->hp == 1)
                          ? 1 // Shedinja: always 1 HP
                          : gen4_calc_stat(true, base->hp, iv_hp, ev_hp, level, 1, 1);
    wr16(dec + 0x8E, max_hp); // current HP (full)
    wr16(dec + 0x90, max_hp); // max HP
    for (int i = 0; i < 5; i++)
    {
        uint8_t iv = gen4_pk4_iv(dec, i + 1);
        uint8_t ev = gen4_pk4_ev(dec, i + 1);
        uint16_t s = gen4_calc_stat(false, nonhp_base[i], iv, ev, level, num[i], den[i]);
        wr16(dec + 0x92 + 2 * i, s); // atk,def,spe,spa,spd at 0x92,0x94,0x96,0x98,0x9A
    }
    return true;
}
